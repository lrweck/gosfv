func TestParseHashFirst(t *testing.T) {
	src := "\xef\xbb\xbf" + `
; generated
// a comment
D41D8CD98F00B204E9800998ECF8427E *dir/file one.bin
900150983CD24FB0D6963F7D28E17F72  two.bin

not a line
`
	p := Parse([]byte(src), hasher.MD5)
	if len(p.Entries) != 2 {
		t.Fatalf("got %d entries: %+v", len(p.Entries), p.Entries)
	}
	if p.Entries[0].Name != "dir/file one.bin" || hexfmt.Upper(p.Entries[0].Hash) != "D41D8CD98F00B204E9800998ECF8427E" {
		t.Errorf("entry 0 = %q %X", p.Entries[0].Name, p.Entries[0].Hash)
	}
	if len(p.Comments) != 1 || p.Comments[0] != "a comment" {
		t.Errorf("comments = %q", p.Comments)
	}
}

