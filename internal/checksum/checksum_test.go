func TestParseCRC32BothOrders(t *testing.T) {
	src := `file one.bin ABCDEF12
file two.bin  12345678
ABCDEF12 *star.bin
12345678 plain.bin
`
	p := Parse([]byte(src), hasher.CRC32)
	want := []struct{ name, hash string }{
		{"file one.bin", "ABCDEF12"},
		{"file two.bin", "12345678"},
		{"star.bin", "ABCDEF12"},
		{"plain.bin", "12345678"},
	}
	if len(p.Entries) != len(want) {
		t.Fatalf("got %d entries: %+v", len(p.Entries), p.Entries)
	}
	for i, w := range want {
		if p.Entries[i].Name != w.name || hexfmt.Upper(p.Entries[i].Hash) != w.hash {
			t.Errorf("entry %d = %q %s, want %q %s", i, p.Entries[i].Name, hexfmt.Upper(p.Entries[i].Hash), w.name, w.hash)
		}
	}
}

