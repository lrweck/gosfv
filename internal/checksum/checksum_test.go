func TestWriteRoundTrip(t *testing.T) {
	dir := t.TempDir()
	sub := filepath.Join(dir, "sub")
	if err := os.MkdirAll(sub, 0o755); err != nil {
		t.Fatal(err)
	}
	files := []model.File{
		{Name: "a.bin", Rel: "a.bin", Dir: dir, Status: model.OK, Hash: []byte{0xde, 0xad, 0xbe, 0xef}},
		{Name: "b.bin", Rel: filepath.Join("sub", "b.bin"), Dir: dir, Status: model.OK, Hash: []byte{1, 2, 3, 4}},
		{Name: "pending", Rel: "pending", Dir: dir, Status: model.Pending},
	}
	out := filepath.Join(dir, "checksums.md5")
	n, err := WriteFile(out, hasher.CRC32, files, WriteOptions{
		Relative: true, SaveDir: dir, Comments: true, Signature: "TEST",
	})
	if err != nil {
		t.Fatal(err)
	}
	if n != 2 {
		t.Fatalf("wrote %d entries", n)
	}
	data, _ := os.ReadFile(out)
	if !bytes.HasPrefix(data, []byte("; Generated by GoSFV (Signature: TEST)\r\n; Algorithm: CRC32\r\n")) {
		t.Errorf("header = %q", data)
	}
	p := Parse(data, hasher.CRC32)
	if len(p.Entries) != 2 {
		t.Fatalf("round trip parsed %+v", p.Entries)
	}
	if p.Entries[0].Name != "a.bin" || hexfmt.Upper(p.Entries[0].Hash) != "DEADBEEF" {
		t.Errorf("entry 0 = %q %s", p.Entries[0].Name, hexfmt.Upper(p.Entries[0].Hash))
	}
	if p.Entries[1].Name != filepath.Join("sub", "b.bin") && p.Entries[1].Name != "sub/b.bin" {
		t.Errorf("entry 1 = %q", p.Entries[1].Name)
	}
}

// TestWriteCRC32StandardByteOrder pins the SFV convention: the eight
// hexadecimal characters are the numeric CRC-32 value written most
// significant nibble first. The byte-reversed form is a .NET hashing
// implementation detail used by old .NET SFV tools, not the SFV format.
func TestWriteCRC32StandardByteOrder(t *testing.T) {
	dir := t.TempDir()
	var b bytes.Buffer
	files := []model.File{{
		Name:   "123456789.bin",
		Rel:    "123456789.bin",
		Dir:    dir,
		Status: model.OK,
		Hash:   []byte{0xCB, 0xF4, 0x39, 0x26}, // CRC-32 of "123456789"
	}}
	if _, err := WriteTo(&b, hasher.CRC32, files, WriteOptions{Relative: true, SaveDir: dir}); err != nil {
		t.Fatal(err)
	}
	const want = "CBF43926 *123456789.bin\r\n"
	if got := b.String(); got != want {
		t.Errorf("WriteTo = %q, want %q", got, want)
	}
	if bytes.Contains(b.Bytes(), []byte("2639F4CB")) {
		t.Error("wrote the legacy little-endian byte order")
	}
}

func TestWriteOnlyOK(t *testing.T) {
	var b bytes.Buffer
	files := []model.File{
		{Name: "ok", Rel: "ok", Dir: t.TempDir(), Status: model.OK, Hash: []byte{1}},
		{Name: "bad", Rel: "bad", Dir: t.TempDir(), Status: model.Bad, Hash: []byte{2}},
	}
	n, err := WriteTo(&b, hasher.CRC32, files, WriteOptions{OnlyOK: true})
	if err != nil || n != 1 {
		t.Fatalf("WriteTo = %d, %v", n, err)
	}
	if bytes.Contains(b.Bytes(), []byte("bad")) {
		t.Errorf("bad entry written: %q", b.Bytes())
	}
}

func TestParseAllocs(t *testing.T) {
	// A smoke test that parsing many lines does not blow up. The arena is
	// the only large allocation; run with -benchmem to inspect.
	line := []byte("D41D8CD98F00B204E9800998ECF8427E *file.bin\n")
	data := bytes.Repeat(line, 10000)
	allocs := testing.AllocsPerRun(3, func() { _ = Parse(data, hasher.MD5) })
	if allocs > 20000 {
		t.Errorf("Parse allocated %v times for 10000 lines", allocs)
	}
}
